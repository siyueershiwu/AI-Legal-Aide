@dataclass(frozen=True)
class RewrittenQuery:
    """query 改写结果。"""

    original: str
    expanded: str          # 拼了法言法语副本的新 query
    law_hint: str | None   # 推断出的可能 law_code（None 表示推断不出来）


def rewrite_query(query: str) -> RewrittenQuery:
    """把白话 query 改成「口语 + 法言法语」复合 query。

    步骤：
    1. 遍历 LAY_QUERY_EXPANSIONS，命中 trigger 的拼接 expansion
    2. 分词去重，把原 query 没出现过的法律术语附加到 query 末尾
    3. 从 SCENARIO_LAW_HINTS 推断 law_code hint（用作窄召回 fallback）
    """
    if not query:
        return RewrittenQuery(query or "", query or "", None)

    extras: list[str] = []
    for pat, exp in LAY_QUERY_EXPANSIONS:
        if pat in query:
            extras.append(exp)

    expanded = query
    if extras:
        # 按空格分词 + 集合去重；过滤掉原 query 已经包含的 token
        seen: set[str] = set()
        tokens: list[str] = []
        for exp in extras:
            for tok in re.split(r"\s+", exp.strip()):
                tok = tok.strip()
                if not tok or tok in query or tok in seen:
                    continue
                seen.add(tok)
                tokens.append(tok)
        if tokens:
            expanded = f"{query} {' '.join(tokens)}"

    # 推断 law hint
    law_hint: str | None = None
    # 优先匹配最长的 trigger（防止 "工资" 盖掉 "拖欠工资"）
    matched_keys: list[tuple[int, str]] = []
    for key in SCENARIO_LAW_HINTS:
        if key in query:
            matched_keys.append((len(key), key))
    if matched_keys:
        matched_keys.sort(reverse=True)
        law_hint = SCENARIO_LAW_HINTS[matched_keys[0][1]]

    return RewrittenQuery(
        original=query,
        expanded=expanded,
        law_hint=law_hint,
    )
